def render_pptx(doc: StudioDocument) -> bytes:
    from pptx import Presentation
    from pptx.chart.data import CategoryChartData
    from pptx.dml.color import RGBColor
    from pptx.enum.chart import XL_CHART_TYPE, XL_LABEL_POSITION
    from pptx.enum.shapes import MSO_CONNECTOR, MSO_SHAPE
    from pptx.enum.text import MSO_ANCHOR, PP_ALIGN
    from pptx.oxml.ns import qn
    from pptx.util import Emu, Inches, Pt

    t = _theme(doc)
    RGB = RGBColor.from_string
    prs = Presentation()
    prs.slide_width, prs.slide_height = Inches(13.333), Inches(7.5)
    SW, SH = prs.slide_width, prs.slide_height
    M = Inches(0.6)  # outer margin
    blank = prs.slide_layouts[6]
    page = {"n": 1}

    # ---------------------------------------------------------------- primitives
    def bg(slide, color):
        f = slide.background.fill
        f.solid()
        f.fore_color.rgb = RGB(color)

    def shape(slide, kind, x, y, w, h, fill, radius=None):
        s = slide.shapes.add_shape(kind, x, y, w, h)
        s.fill.solid()
        s.fill.fore_color.rgb = RGB(fill)
        s.line.fill.background()
        s.shadow.inherit = False
        if radius is not None and kind == MSO_SHAPE.ROUNDED_RECTANGLE:
            s.adjustments[0] = radius
        return s

    def text(
        slide,
        x,
        y,
        w,
        h,
        value,
        size=16,
        color=None,
        bold=False,
        font=None,
        align=PP_ALIGN.LEFT,
        anchor=MSO_ANCHOR.TOP,
        italic=False,
    ):
        tb = slide.shapes.add_textbox(x, y, w, h)
        tf = tb.text_frame
        tf.word_wrap = True
        tf.margin_left = tf.margin_right = tf.margin_top = tf.margin_bottom = 0
        tf.vertical_anchor = anchor
        p = tf.paragraphs[0]
        p.alignment = align
        r = p.add_run()
        r.text = value
        r.font.size = Pt(size)
        r.font.bold = bold
        r.font.italic = italic
        r.font.name = font or t.body_font
        r.font.color.rgb = RGB(color or t.ink)
        return tf

    def fit(value: str, base: int, max_chars: int, floor: int) -> int:
        """Shrink the font for long text instead of letting it overflow."""
        n = len(value)
        if n <= max_chars:
            return base
        return max(floor, int(base * (max_chars / n) ** 0.5))

    def bullet_list(slide, items: List[str], x, y, w, h, size=18, color=None):
        tb = slide.shapes.add_textbox(x, y, w, h)
        tf = tb.text_frame
        tf.word_wrap = True
        tf.margin_left = tf.margin_right = tf.margin_top = tf.margin_bottom = 0
        total = sum(len(i) for i in items)
        size = size if total < 260 else max(14, size - 3)
        for i, item in enumerate(items):
            p = tf.paragraphs[0] if i == 0 else tf.add_paragraph()
            p.space_after = Pt(12)
            pPr = p._p.get_or_add_pPr()
            pPr.set("marL", str(Emu(Inches(0.3))))
            pPr.set("indent", str(-Emu(Inches(0.3))))
            bu_clr = pPr.makeelement(qn("a:buClr"), {})
            srgb = bu_clr.makeelement(qn("a:srgbClr"), {"val": t.accent})
            bu_clr.append(srgb)
            pPr.append(bu_clr)
            pPr.append(pPr.makeelement(qn("a:buFont"), {"typeface": "Arial"}))
            pPr.append(pPr.makeelement(qn("a:buChar"), {"char": "•"}))
            r = p.add_run()
            r.text = item
            r.font.size = Pt(size)
            r.font.name = t.body_font
            r.font.color.rgb = RGB(color or t.ink)

    def title(slide, value: str, subtitle: str = ""):
        text(
            slide,
            M,
            Inches(0.55),
            SW - 2 * M,
            Inches(0.9),
            value,
            fit(value, 36, 48, 26),
            t.primary,
            True,
            t.head_font,
            anchor=MSO_ANCHOR.BOTTOM,
        )
        if subtitle:
            text(slide, M, Inches(1.5), SW - 2 * M, Inches(0.5), subtitle, 16, t.muted)

    def footer(slide, dark=False):
        page["n"] += 1
        c = "A1A1AA" if dark else t.muted
        text(
            slide,
            M,
            SH - Inches(0.45),
            Inches(8),
            Inches(0.3),
            f"{PRODUCT}  ·  {doc.title[:70]}",
            10,
            c,
        )
        text(
            slide,
            SW - M - Inches(1),
            SH - Inches(0.45),
            Inches(1),
            Inches(0.3),
            str(page["n"]),
            10,
            c,
            align=PP_ALIGN.RIGHT,
        )

    def notes(slide, value: str):
        if value and doc.options.speaker_notes:
            slide.notes_slide.notes_text_frame.text = value

    def number_badge(slide, x, y, n, d=Inches(0.55), fill=None, fg=None):
        c = shape(slide, MSO_SHAPE.OVAL, x, y, d, d, fill or t.primary)
        tf = c.text_frame
        tf.margin_left = tf.margin_right = tf.margin_top = tf.margin_bottom = 0
        p = tf.paragraphs[0]
        p.alignment = PP_ALIGN.CENTER
        r = p.add_run()
        r.text = str(n)
        r.font.size = Pt(16)
        r.font.bold = True
        r.font.name = t.head_font
        r.font.color.rgb = RGB(fg or "FFFFFF")
        tf.vertical_anchor = MSO_ANCHOR.MIDDLE

    def logo_card(slide, x, y, h=Inches(0.9)):
        if not LOGO_PATH.exists():
            return
        w = int(h * 1.92)
        shape(slide, MSO_SHAPE.ROUNDED_RECTANGLE, x, y, w, h, "FFFFFF", 0.12)
        pad = Inches(0.08)
        slide.shapes.add_picture(str(LOGO_PATH), x + pad, y + pad, height=h - 2 * pad)

    content_top = Inches(1.9)
    content_h = SH - content_top - Inches(0.9)
    content_w = SW - 2 * M

    # ---------------------------------------------------------------- layouts
    def l_bullets(s, sl: Slide, idx: int):
        title(s, sl.title, sl.subtitle)
        left_w = int(content_w * 0.6)
        bullet_list(s, sl.bullets[:6], M, content_top, left_w, content_h, 20)
        px = M + left_w + Inches(0.5)
        pw = content_w - left_w - Inches(0.5)
        ph = min(content_h, Inches(3.6))
        shape(s, MSO_SHAPE.ROUNDED_RECTANGLE, px, content_top, pw, ph, t.soft, 0.06)
        lead = sl.bullets[0] if sl.bullets else sl.title
        m = LEAD_NUMBER.match(lead)
        big, rest = (
            (m.group(1).strip(), m.group(2).strip() or lead)
            if m
            else (f"{idx:02d}", lead)
        )
        if getattr(sl, "image_path", None) and os.path.exists(sl.image_path):
            try:
                s.shapes.add_picture(
                    sl.image_path,
                    px + Inches(0.1),
                    content_top + Inches(0.1),
                    width=pw - Inches(0.2),
                )
                cap = getattr(sl, "image_caption", "") or "Visual evidence"
                text(
                    s,
                    px,
                    content_top + ph + Inches(0.1),
                    pw,
                    Inches(0.4),
                    cap,
                    11,
                    t.muted,
                    italic=True,
                )
            except Exception:
                pass
        else:
            text(
                s,
                px + Inches(0.4),
                content_top + Inches(0.35),
                pw - Inches(0.8),
                Inches(1.4),
                big,
                fit(big, 60, 7, 34),
                t.accent,
                True,
                t.head_font,
            )
            text(
                s,
                px + Inches(0.4),
                content_top + Inches(1.8),
                pw - Inches(0.8),
                ph - Inches(2.0),
                rest,
                fit(rest, 18, 80, 13),
                t.primary,
                False,
                t.head_font,
            )

    def l_cards(s, sl: Slide, idx: int):
        title(s, sl.title, sl.subtitle)
        items = sl.bullets[:4]
        n = len(items)
        cols = 2 if n == 4 else n
        rows = 2 if n == 4 else 1
        gap = Inches(0.35)
        cw = int((content_w - gap * (cols - 1)) / cols)
        ch = int((content_h - gap * (rows - 1)) / rows)
        if not any(":" in it for it in items):
            ch = min(ch, Inches(2.0))
        for i, item in enumerate(items):
            r_, c_ = divmod(i, cols)
            x = M + c_ * (cw + gap)
            y = content_top + r_ * (ch + gap)
            shape(s, MSO_SHAPE.ROUNDED_RECTANGLE, x, y, cw, ch, t.soft, 0.08)
            number_badge(s, x + Inches(0.35), y + Inches(0.35), i + 1)
            head, _, rest = item.partition(":")
            if not rest:
                head, rest = item, ""
            text(
                s,
                x + Inches(0.35),
                y + Inches(1.1),
                cw - Inches(0.7),
                Inches(0.6),
                head.strip(),
                fit(head, 20, 40, 15),
                t.primary,
                True,
                t.head_font,
            )
            if rest:
                text(
                    s,
                    x + Inches(0.35),
                    y + Inches(1.75),
                    cw - Inches(0.7),
                    ch - Inches(2.0),
                    rest.strip(),
                    fit(rest, 15, 120, 12),
                    t.ink,
                )

    def l_stats(s, sl: Slide, idx: int):
        title(s, sl.title, sl.subtitle)
        stats = sl.stats[:4]
        gap = Inches(0.35)
        cap = Inches(3.8) if (sl.bullets or len(stats) >= 3) else Inches(5.9)
        cw = min(int((content_w - gap * (len(stats) - 1)) / len(stats)), cap)
        ch = Inches(2.9)
        y = content_top + Inches(0.3)
        for i, st in enumerate(stats):
            x = M + i * (cw + gap)
            shape(s, MSO_SHAPE.ROUNDED_RECTANGLE, x, y, cw, ch, t.soft, 0.06)
            text(
                s,
                x + Inches(0.4),
                y + Inches(0.45),
                cw - Inches(0.8),
                Inches(1.3),
                st.value,
                fit(st.value, 56, 6, 30),
                t.primary,
                True,
                t.head_font,
            )
            text(
                s,
                x + Inches(0.4),
                y + Inches(1.85),
                cw - Inches(0.8),
                Inches(0.9),
                st.label,
                fit(st.label, 17, 45, 12),
                t.muted,
            )
        used = len(stats) * cw + gap * (len(stats) - 1)
        extra = sl.bullets[:4]
        if extra and used < content_w - Inches(3):
            bx = M + used + Inches(0.6)
            bullet_list(
                s, extra, bx, y + Inches(0.2), content_w - used - Inches(0.6), ch, 17
            )
        elif extra:
            text(
                s,
                M,
                y + ch + Inches(0.35),
                content_w,
                Inches(0.6),
                extra[0],
                15,
                t.ink,
                italic=True,
            )

    def l_chart(s, sl: Slide, idx: int):
        title(s, sl.title, sl.subtitle)
        data = CategoryChartData()
        data.categories = sl.chart_labels[:8]
        data.add_series("Value", sl.chart_values[:8])
        cw = int(content_w * 0.68)
        gf = s.shapes.add_chart(
            XL_CHART_TYPE.COLUMN_CLUSTERED, M, content_top, cw, content_h, data
        )
        ch = gf.chart
        ch.has_legend = False
        ch.has_title = False
        plot = ch.plots[0]
        plot.gap_width = 70
        plot.has_data_labels = True
        dl = plot.data_labels
        dl.font.size = Pt(13)
        dl.font.bold = True
        dl.font.color.rgb = RGB(t.ink)
        dl.position = XL_LABEL_POSITION.OUTSIDE_END
        ser = plot.series[0]
        ser.format.fill.solid()
        ser.format.fill.fore_color.rgb = RGB(t.primary)
        va = ch.value_axis
        va.has_major_gridlines = False
        va.visible = False
        ca = ch.category_axis
        ca.tick_labels.font.size = Pt(12)
        ca.tick_labels.font.color.rgb = RGB(t.muted)
        ca.format.line.fill.background()
        px = M + cw + Inches(0.4)
        pw = content_w - cw - Inches(0.4)
        shape(
            s, MSO_SHAPE.ROUNDED_RECTANGLE, px, content_top, pw, content_h, t.soft, 0.06
        )
        top_i = max(range(len(sl.chart_values)), key=lambda i: sl.chart_values[i])
        text(
            s,
            px + Inches(0.35),
            content_top + Inches(0.4),
            pw - Inches(0.7),
            Inches(1.1),
            f"{sl.chart_values[top_i]:g}",
            44,
            t.accent,
            True,
            t.head_font,
        )
        text(
            s,
            px + Inches(0.35),
            content_top + Inches(1.5),
            pw - Inches(0.7),
            Inches(0.8),
            f"Highest: {sl.chart_labels[top_i]}",
            15,
            t.muted,
        )
        if sl.bullets:
            bullet_list(
                s,
                sl.bullets[:3],
                px + Inches(0.35),
                content_top + Inches(2.4),
                pw - Inches(0.7),
                content_h - Inches(2.6),
                14,
            )

    def l_columns(s, sl: Slide, idx: int, comparison=False):
        title(s, sl.title, sl.subtitle)
        gap = Inches(0.4)
        cw = int((content_w - gap) / 2)
        rows = max(len(sl.left[:5]), len(sl.right[:5]), 1)
        chh = min(content_h, max(Inches(2.6), Inches(1.5) + Inches(0.62) * rows))
        for i, (head, items) in enumerate(
            ((sl.left_title, sl.left), (sl.right_title, sl.right))
        ):
            x = M + i * (cw + gap)
            highlight = comparison and i == 1
            fill = t.primary if highlight else t.soft
            fg = "FFFFFF" if highlight else t.ink
            hc = "FFFFFF" if highlight else t.primary
            shape(s, MSO_SHAPE.ROUNDED_RECTANGLE, x, content_top, cw, chh, fill, 0.05)
            text(
                s,
                x + Inches(0.45),
                content_top + Inches(0.4),
                cw - Inches(0.9),
                Inches(0.6),
                head or ("Option " + "AB"[i]),
                22,
                hc,
                True,
                t.head_font,
            )
            bullet_list(
                s,
                items[:5],
                x + Inches(0.45),
                content_top + Inches(1.2),
                cw - Inches(0.9),
                chh - Inches(1.4),
                18,
                fg,
            )

    def l_process(s, sl: Slide, idx: int):
        title(s, sl.title, sl.subtitle)
        steps = sl.steps[:5]
        n = len(steps)
        seg = int(content_w / n)
        d = Inches(0.9)
        cy = content_top + Inches(0.6)
        line = s.shapes.add_connector(
            MSO_CONNECTOR.STRAIGHT,
            M + int(seg / 2),
            cy + int(d / 2),
            M + int(seg * (n - 0.5)),
            cy + int(d / 2),
        )
        line.line.color.rgb = RGB(t.soft if t.soft != "FFFFFF" else "E4E4E7")
        line.line.width = Pt(4)
        for i, step in enumerate(steps):
            cx = M + seg * i + int(seg / 2) - int(d / 2)
            number_badge(s, cx, cy, i + 1, d, t.primary if i < n - 1 else t.accent)
            head, _, rest = step.partition(":")
            text(
                s,
                M + seg * i + Inches(0.15),
                cy + d + Inches(0.35),
                seg - Inches(0.3),
                Inches(0.7),
                head.strip(),
                fit(head, 18, 28, 13),
                t.primary,
                True,
                t.head_font,
                align=PP_ALIGN.CENTER,
            )
            if rest:
                text(
                    s,
                    M + seg * i + Inches(0.15),
                    cy + d + Inches(1.1),
                    seg - Inches(0.3),
                    Inches(1.8),
                    rest.strip(),
                    fit(rest, 14, 90, 11),
                    t.muted,
                    align=PP_ALIGN.CENTER,
                )

    def l_quote(s, sl: Slide, idx: int):
        bg(s, t.soft)
        text(
            s,
            M + Inches(0.4),
            Inches(0.4),
            Inches(2),
            Inches(2.4),
            "\u201c",
            140,
            t.accent,
            True,
            "Georgia",
        )
        text(
            s,
            M + Inches(1.2),
            Inches(2.3),
            content_w - Inches(2.4),
            Inches(3),
            sl.quote,
            fit(sl.quote, 32, 120, 20),
            t.primary,
            False,
            t.head_font,
            italic=True,
        )
        text(
            s,
            M + Inches(1.2),
            Inches(5.5),
            content_w - Inches(2.4),
            Inches(0.5),
            sl.title,
            16,
            t.muted,
            True,
        )

    def l_table(s, sl: Slide, idx: int):
        title(s, sl.title, sl.subtitle)
        cols = [str(c) for c in sl.table_columns] if sl.table_columns else ["Data"]
        raw_rows = sl.table_rows or []
        if not raw_rows and sl.bullets:
            raw_rows = [[b] for b in sl.bullets]
        num_cols = min(len(cols), 8)
        num_rows = min(len(raw_rows) + 1, 9)
        if num_cols < 1 or num_rows < 2:
            return l_bullets(s, sl, idx)

        tx = M
        ty = content_top + Inches(0.1)
        tw = content_w
        th = min(content_h - Inches(0.4), Inches(0.5) * num_rows)

        tbl_shape = s.shapes.add_table(num_rows, num_cols, tx, ty, tw, th)
        tbl = tbl_shape.table

        col_w = int(tw / num_cols)
        for c_i in range(num_cols):
            tbl.columns[c_i].width = col_w

        # Header row
        for c_i in range(num_cols):
            cell = tbl.cell(0, c_i)
            cell.fill.solid()
            cell.fill.fore_color.rgb = RGB(t.primary)
            tf = cell.text_frame
            tf.word_wrap = True
            tf.margin_left = tf.margin_right = Inches(0.12)
            tf.margin_top = tf.margin_bottom = Inches(0.1)
            tf.vertical_anchor = MSO_ANCHOR.MIDDLE
            p = tf.paragraphs[0]
            p.alignment = PP_ALIGN.LEFT
            r = p.add_run()
            r.text = cols[c_i]
            r.font.bold = True
            r.font.size = Pt(13)
            r.font.name = t.head_font
            r.font.color.rgb = RGB("FFFFFF")

        # Data rows
        for r_i, row_data in enumerate(raw_rows[: num_rows - 1], start=1):
            is_even = r_i % 2 == 0
            bg_col = t.soft if is_even else "FFFFFF"
            for c_i in range(num_cols):
                cell = tbl.cell(r_i, c_i)
                cell.fill.solid()
                cell.fill.fore_color.rgb = RGB(bg_col)
                tf = cell.text_frame
                tf.word_wrap = True
                tf.margin_left = tf.margin_right = Inches(0.12)
                tf.margin_top = tf.margin_bottom = Inches(0.08)
                tf.vertical_anchor = MSO_ANCHOR.MIDDLE
                val = str(row_data[c_i]) if c_i < len(row_data) else ""
                p = tf.paragraphs[0]
                p.alignment = PP_ALIGN.LEFT
                r = p.add_run()
                r.text = val
                r.font.size = Pt(11)
                r.font.name = t.body_font
                r.font.color.rgb = RGB(t.ink)

        if sl.bullets:
            by = ty + th + Inches(0.2)
            bh = SH - by - Inches(0.5)
            if bh > Inches(0.35):
                text(
                    s,
                    M,
                    by,
                    content_w,
                    bh,
                    "Note: " + sl.bullets[0],
                    12,
                    t.muted,
                    italic=True,
                )

    def l_image(s, sl: Slide, idx: int):
        title(s, sl.title, sl.subtitle)
        img_path = getattr(sl, "image_path", "")
        if not img_path or not os.path.exists(img_path):
            return l_bullets(s, sl, idx)

        max_iw = int(content_w * 0.52)
        max_ih = content_h - Inches(0.5)
        try:
            from PIL import Image as PILImg

            with PILImg.open(img_path) as pim:
                pw_px, ph_px = pim.size
            aspect = pw_px / max(1, ph_px)
        except Exception:
            aspect = 1.33

        if aspect > (max_iw / max_ih):
            actual_w = max_iw
            actual_h = int(max_iw / aspect)
        else:
            actual_h = max_ih
            actual_w = int(max_ih * aspect)

        ix = M
        iy = content_top + int((content_h - actual_h) / 2)

        shape(
            s,
            MSO_SHAPE.ROUNDED_RECTANGLE,
            ix - Inches(0.06),
            iy - Inches(0.06),
            actual_w + Inches(0.12),
            actual_h + Inches(0.12),
            t.soft,
            0.04,
        )
        s.shapes.add_picture(img_path, ix, iy, width=actual_w, height=actual_h)

        cap = (
            getattr(sl, "image_caption", "") or f"Figure {idx}: Visual source evidence"
        )
        text(
            s,
            ix,
            iy + actual_h + Inches(0.1),
            actual_w,
            Inches(0.4),
            cap,
            11,
            t.muted,
            italic=True,
        )

        rx = M + actual_w + Inches(0.5)
        rw = content_w - actual_w - Inches(0.5)
        bullets = (
            sl.bullets
            or sl.steps
            or ([sl.subtitle, sl.notes] if sl.subtitle or sl.notes else [])
        )
        if bullets:
            bullet_list(
                s, bullets[:5], rx, content_top + Inches(0.2), rw, content_h, 18
            )
        elif sl.notes:
            text(
                s,
                rx,
                content_top + Inches(0.4),
                rw,
                content_h - Inches(1),
                sl.notes,
                16,
                t.ink,
            )

    layouts = {
        "bullets": l_bullets,
        "cards": l_cards,
        "stats": l_stats,
        "chart": l_chart,
        "two_column": l_columns,
        "comparison": lambda s, sl, i: l_columns(s, sl, i, True),
        "process": l_process,
        "quote": l_quote,
        "table": l_table,
        "image": l_image,
    }

    # ---------------------------------------------------------------- cover
    s = prs.slides.add_slide(blank)
    bg(s, t.dark)
    logo_card(s, M, Inches(0.55))
    text(
        s,
        M,
        Inches(2.7),
        Inches(10),
        Inches(0.4),
        _label(doc).upper(),
        14,
        t.accent,
        True,
    )
    text(
        s,
        M,
        Inches(3.15),
        Inches(11.5),
        Inches(2.0),
        doc.title,
        fit(doc.title, 48, 45, 32),
        t.on_dark,
        True,
        t.head_font,
    )
    if doc.subtitle:
        text(s, M, Inches(5.25), Inches(11), Inches(0.8), doc.subtitle, 20, "D4D4D8")
    text(
        s,
        M,
        SH - Inches(0.75),
        Inches(10),
        Inches(0.4),
        f"{ORG}  ·  {doc.generated_at}",
        12,
        "A1A1AA",
    )
    notes(s, doc.summary)

    slides = doc.slides
    if not slides:  # non-deck documents rendered as PPTX: derive slides from sections
        slides = []
        if doc.stats:
            slides.append(
                Slide(layout="stats", title="Key figures", stats=doc.stats[:4])
            )
        for sec in _sections_for(doc):
            slides.append(
                Slide(
                    layout="bullets",
                    title=sec.heading,
                    bullets=sec.bullets or [sec.body],
                )
            )
        if doc.recommendations:
            slides.append(
                Slide(
                    layout="cards",
                    title="Recommendations",
                    bullets=doc.recommendations[:4],
                )
            )

    # ---------------------------------------------------------------- agenda
    if doc.kind == "presentation" and doc.options.slide_count >= 8 and len(slides) >= 4:
        s = prs.slides.add_slide(blank)
        bg(s, t.light)
        title(s, "Agenda")
        items = [sl.title for sl in slides][:10]
        per_col = (len(items) + 1) // 2
        cw = int((content_w - Inches(0.6)) / 2)
        for i, it in enumerate(items):
            c_, r_ = divmod(i, per_col)
            x = M + c_ * (cw + Inches(0.6))
            y = content_top + r_ * Inches(0.85)
            number_badge(s, x, y, i + 1, Inches(0.5), t.soft, t.primary)
            text(
                s,
                x + Inches(0.75),
                y,
                cw - Inches(0.8),
                Inches(0.5),
                it,
                fit(it, 18, 45, 13),
                t.ink,
                anchor=MSO_ANCHOR.MIDDLE,
            )
        footer(s)

    for i, sl in enumerate(slides, 1):
        s = prs.slides.add_slide(blank)
        bg(s, t.light)
        layouts.get(sl.layout, l_bullets)(s, sl, i)
        footer(s)
        notes(s, sl.notes)

    # ---------------------------------------------------------------- closing
    s = prs.slides.add_slide(blank)
    bg(s, t.dark)
    recs = doc.recommendations[:3]
    top = Inches(1.0) if recs else Inches(2.4)
    text(s, M, top, Inches(10), Inches(0.4), "CONCLUSION", 14, t.accent, True)
    concl = doc.conclusion or doc.summary or "Thank you."
    text(
        s,
        M,
        top + Inches(0.5),
        Inches(11.5),
        Inches(2.2),
        concl,
        fit(concl, 32, 110, 20),
        t.on_dark,
        False,
        t.head_font,
    )
    if recs:
        gap = Inches(0.35)
        cw = int((content_w - gap * (len(recs) - 1)) / len(recs))
        card_fill = t.primary if t.primary != t.dark else "27272A"
        for i, r_ in enumerate(recs):
            x = M + i * (cw + gap)
            shape(
                s,
                MSO_SHAPE.ROUNDED_RECTANGLE,
                x,
                Inches(4.2),
                cw,
                Inches(2.2),
                card_fill,
                0.06,
            )
            number_badge(s, x + Inches(0.3), Inches(4.45), i + 1, Inches(0.5), t.accent)
            text(
                s,
                x + Inches(0.3),
                Inches(5.1),
                cw - Inches(0.6),
                Inches(1.2),
                r_,
                fit(r_, 15, 90, 11),
                "FFFFFF",
            )
    footer(s, dark=True)

    buf = io.BytesIO()
    prs.save(buf)
    return buf.getvalue()


